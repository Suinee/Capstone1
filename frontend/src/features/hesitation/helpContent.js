export function getKioskHelpContent(screenId, helpKey, task) {
  const context = task.context ?? {};
  const content = (title, short, detail) => ({ title, levels: [short, detail] });
  if (helpKey === "choose-menu") {
    return context.category === "BURGER"
      ? content("메뉴 선택", "메뉴를 고민 중이신가요? 카드를 눌러 구성을 확인해 보세요.",
          "원하는 버거 카드를 누르면 단품·세트의 가격과 구성을 확인할 수 있어요. 사이드와 음료도 원하면 세트를 선택하세요.")
      : content("메뉴 선택", "메뉴를 고민 중이신가요? 이름과 가격을 확인해 보세요.",
          "사이드·음료 카드를 누르면 해당 메뉴 1개가 바로 주문서에 담깁니다. 주문서에서 수정하거나 삭제할 수 있어요.");
  }
  if (["choose-type", "choose-size"].includes(helpKey)) {
    const detail = helpKey === "choose-type"
      ? "버거만 원하면 ‘단품 선택’, 사이드와 음료도 원하면 ‘세트 선택’을 누르세요."
      : "표시된 메뉴 이름과 가격을 확인한 뒤 원하는 세트 크기를 누르세요.";
    return content("주문 구성 선택", "원하는 구성을 골라 주세요.",
      detail + (context.isEditing ? " 선택 후 ‘수정하기’를 눌러 주세요." : ""));
  }
  if (["choose-side", "choose-drink"].includes(helpKey)) {
    const label = helpKey === "choose-side" ? "사이드" : "음료";
    return content(`${label} 선택`, `${label}를 고민 중이신가요? 원하는 카드를 눌러 주세요.`,
      `메뉴와 표시된 추가금을 확인한 뒤 선택하세요. 선택 표시를 확인하고 ‘${context.isEditing ? "수정하기" : "다음"}’를 눌러 주세요.`);
  }
  const action = ACTION_HELP[helpKey];
  return action ? content(...action) : HELP_CONTENT[screenId] ?? DEFAULT_HELP_CONTENT;
}
